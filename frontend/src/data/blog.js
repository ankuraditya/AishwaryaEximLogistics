export const getBlogPostBySlug = (
  slug
) =>
  blogPosts.find(
    (post) =>
      post.slug === slug
  );

export const getBlogCategory = (
  slug
) =>
  blogCategories.find(
    (category) =>
      category.slug === slug
  );

export const getFeaturedBlogPost =
  () =>
    blogPosts.find(
      (post) => post.featured
    ) || blogPosts[0] || null;

export const getRelatedBlogPosts = (
  post,
  limit = 3
) =>
  blogPosts
    .filter(
      (item) =>
        item.id !== post.id &&
        item.categorySlug ===
          post.categorySlug
    )
    .concat(
      blogPosts.filter(
        (item) =>
          item.id !== post.id &&
          item.categorySlug !==
            post.categorySlug
      )
    )
    .slice(0, limit);

export const estimateReadingTime = (
  post
) => {
  if (!post) {
    return 1;
  }

  const text =
    post.content
      .flatMap((block) => {
        if (
          block.type === "list"
        ) {
          return block.items;
        }

        return [
          block.text || "",
        ];
      })
      .join(" ");

  const words =
    text
      .trim()
      .split(/\s+/)
      .filter(Boolean)
      .length;

  return Math.max(
    1,
    Math.ceil(words / 200)
  );
};